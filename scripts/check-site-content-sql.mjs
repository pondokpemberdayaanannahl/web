import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { PGlite } = await import(pathToFileURL(require.resolve('@electric-sql/pglite', { paths:[resolve('.backend-backups/sql-test-runtime')] })).href);
const db = new PGlite();
const migration = readFileSync('supabase/migrations/202610270003_site_content.sql','utf8');
try {
  await db.exec(`create role anon; create role authenticated; create schema private; create schema auth;
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    create table public.pengurus(id uuid primary key,role text,active boolean);
    insert into public.pengurus values('00000000-0000-4000-8000-000000000001','admin',true),('00000000-0000-4000-8000-000000000002','editor',true),('00000000-0000-4000-8000-000000000003','admin',false);
    create function private.pengurus_role() returns text language sql stable security definer set search_path='' as $$ select role from public.pengurus where id=(select auth.uid()) and active $$;
    grant usage on schema private,auth to anon,authenticated; grant execute on function private.pengurus_role() to anon,authenticated;`);
  await db.exec(migration);
  const content = { version:1,values:{ title:'Diterbitkan' },hidden:[] };
  const save = (doc,draft,published,publish) => db.query('select public.save_site_content($1,$2,$3,$4,$5) as result',['beranda',doc,draft,published,publish]);
  await db.exec("set role anon");
  await assert.rejects(save(content,0,0,true), /permission denied/);
  await db.exec("set role authenticated; select set_config('request.jwt.claim.sub','00000000-0000-4000-8000-000000000002',false)");
  await assert.rejects(save(content,0,0,true), /Hanya admin/);
  await db.exec("select set_config('request.jwt.claim.sub','00000000-0000-4000-8000-000000000003',false)");
  await assert.rejects(save(content,0,0,true), /Hanya admin/);
  await db.exec("select set_config('request.jwt.claim.sub','00000000-0000-4000-8000-000000000001',false)");
  await save(content,0,0,false);
  await db.exec('set role anon');
  assert.equal((await db.query('select * from public.site_content')).rows.length,0);
  await db.exec('set role authenticated');
  const published = (await save(content,1,0,true)).rows[0].result;
  assert.equal(published.draft.revision,2); assert.equal(published.published.revision,1);
  await save({ ...content,values:{ title:'PRIVAT DRAFT' } },2,1,false);
  await db.exec('set role anon');
  const publicRows = (await db.query('select content,state from public.site_content')).rows;
  assert.equal(publicRows.length,1); assert.equal(publicRows[0].content.values.title,'Diterbitkan');
  await assert.rejects(db.query('update public.site_content set revision=999'), /permission denied/);
  await assert.rejects(db.query('select * from public.site_content_history'), /permission denied/);
  await db.exec("set role authenticated; select set_config('request.jwt.claim.sub','00000000-0000-4000-8000-000000000002',false)");
  assert.equal((await db.query('select * from public.site_content')).rows.length,1);
  assert.equal((await db.query('select * from public.site_content_history')).rows.length,0);
  await db.exec("select set_config('request.jwt.claim.sub','00000000-0000-4000-8000-000000000001',false)");
  await assert.rejects(save(content,2,1,true), /diubah/);
  await assert.rejects(save({ version:1,values:{bad:[]},hidden:[] },3,1,true), /belum sesuai/);
  assert.equal((await db.query('select count(*)::int as n from public.site_content_history')).rows[0].n,1);
  await db.exec('reset role'); await db.exec(migration);
  assert.equal((await db.query('select count(*)::int as n from public.site_content')).rows[0].n,2);
  console.log('PASS (local PostgreSQL): admin-only saves, private drafts, public published content, atomic revisions, history privacy, invalid payload rejection, and repeatable migration. No remote database contacted.');
} finally { await db.close(); }
